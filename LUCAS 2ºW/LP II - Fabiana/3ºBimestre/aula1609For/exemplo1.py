#exibindo 'olá' 5 vezes na tela
for i in range (5):
    print("Olá")

#exibindo 'olá' 4 vezes na tela
print ("-" * 30)
for i in range (1, 5):
    print("Olá")

#exibindo de 0 a 5 na tela
print("-" * 30)
for i in range (6):
    print(i)

#exibindo de 1 até 10 pulando de 2 em 2
print("-" * 30)
for i in range(0, 11, 2):
    print(i)

#fazendo uma de 0 até 50 pulando de 5 em 5
print("-" * 30)
for numero in range(0, 51, 3):
    print(numero)

#fazendo uma contagem regressiva - 10 até 1
print("-" * 30)
for numero in range (10, 0,-1):
    print(numero)
#fazendo uma contagem regressiva - 10 até 0
print("-" * 30)
for numero in range (10, -1, -1):
    print(numero)
